export type IconName = keyof typeof ICON_MAP;

/** Resolve a lucide icon component by name. Returns null if not found. */
export function getScopeIcon(name: string): LucideIcon | null {
  return ICON_MAP[name] ?? null;
}

/** Alphabetically sorted list of available icon names (for pickers). */
export const AVAILABLE_ICON_NAMES: IconName[] = (
  Object.keys(ICON_MAP) as IconName[]
).sort((a, b) => a.localeCompare(b));
